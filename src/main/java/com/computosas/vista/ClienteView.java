    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
// REEMPLAZAR LO QUE ESTÉ DENTRO DEL MÉTODO DEL BOTÓN REGISTRAR CON ESTO:
try {
    // 1. VALIDACIÓN: Verificar que los campos no estén vacíos en la interfaz
    if (txtIdCliente.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty() ||
        txtDireccion.getText().trim().isEmpty() || txtTelefono.getText().trim().isEmpty() ||
        txtCorreo.getText().trim().isEmpty()) {
        
        javax.swing.JOptionPane.showMessageDialog(this, "Todos los campos de registro son obligatorios.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. CAPTURA DE DATOS DESDE LOS TEXTFIELDS
    int idCliente = Integer.parseInt(txtIdCliente.getText().trim());
    String nombre = txtNombre.getText().trim();
    String direccion = txtDireccion.getText().trim();
    String telefono = txtTelefono.getText().trim();
    String correo = txtCorreo.getText().trim();

    // 3. CONSTRUIR INSTANCIA DEL MODELO CLIENTE
    com.computosas.modelo.Cliente nuevoCliente = new com.computosas.modelo.Cliente(idCliente, nombre, direccion, telefono, correo);
    com.computosas.dao.ClienteDao clienteDao = new com.computosas.dao.ClienteDao();

    // 4. PREVENCIÓN DE DUPLICADOS: Verificar si la cédula/NIT ya existe en Neon Cloud
    if (clienteDao.buscarClientePorId(idCliente) != null) {
        javax.swing.JOptionPane.showMessageDialog(this, "El ID/Cédula " + idCliente + " ya se encuentra registrado en el sistema.", "Registro Duplicado", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 5. PERSISTENCIA: Invocar al DAO para insertar en PostgreSQL
    boolean exito = clienteDao.registrarCliente(nuevoCliente);

    if (exito) {
        javax.swing.JOptionPane.showMessageDialog(this, "¡Cliente registrado exitosamente en CÓMPUTO S.A.S.!", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        
        // 6. LIMPIEZA AUTOMÁTICA DE CAMPOS
        txtIdCliente.setText("");
        txtNombre.setText("");
        txtDireccion.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        
        // 7. RECARGAR LA TABLA VISUAL (Opcional: Si tienes un método para listar en JTable, llámalo aquí)
        // ejemplo: de_vuelta_a_cargar_tabla_clientes();
        
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Error crítico: No se pudo conectar con el servidor para guardar el registro.", "Error de Almacenamiento", javax.swing.JOptionPane.ERROR_MESSAGE);
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "El campo de ID/Cédula debe ser un valor netamente numérico sin puntos ni letras.", "Error de Formato", javax.swing.JOptionPane.ERROR_MESSAGE);
} catch (HeadlessException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Fallo inesperado en el módulo de control: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnRegistrarActionPerformed

