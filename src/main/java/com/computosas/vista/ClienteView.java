    private void tablaClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaClientesMouseClicked
// 1. Conseguir la fila sobre la que el usuario hizo clic
    int filaSeleccionada = tablaClientes.getSelectedRow();
    
    // 2. Si la fila es válida (mayor o igual a 0) extraemos los datos
    if (filaSeleccionada >= 0) {
        // La columna 0 de tu JTable contiene el ID_CLIENTE
        String id = tablaClientes.getValueAt(filaSeleccionada, 0).toString();
        String nombre = tablaClientes.getValueAt(filaSeleccionada, 1).toString();
        String direccion = tablaClientes.getValueAt(filaSeleccionada, 2).toString();
        String telefono = tablaClientes.getValueAt(filaSeleccionada, 3).toString();
        String correo = tablaClientes.getValueAt(filaSeleccionada, 4).toString();
        
        // 3. PASAR LOS DATOS A LOS COMPONENTES REALES
        txtIdCliente.setText(id); // <-- ¡Esto solucionará la carga del ID de una!
        txtNombre.setText(nombre);
        txtDireccion.setText(direccion);
        txtTelefono.setText(telefono);
        txtCorreo.setText(correo);
        
        // Deshabilitamos el campo del ID para que no lo editen por error al actualizar
        txtIdCliente.setEditable(false);
    }
    }

    /**
     * Consulta el listado completo mediante el DAO y actualiza el JTable en tiempo real.
     */
    public void cargarTablaClientes() {
        com.computosas.dao.ClienteDao dao = new com.computosas.dao.ClienteDao();
        java.util.List<com.computosas.modelo.Cliente> lista = dao.listarClientes();
        
        // Obtenemos el modelo estructural de la tabla de clientes
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaClientes.getModel();
        modelo.setRowCount(0); // Limpiamos la grilla para evitar duplicados visuales
        
        // Insertamos fila por fila con los datos provenientes de Neon Cloud
        for (com.computosas.modelo.Cliente c : lista) {
            Object[] fila = new Object[]{
                c.getIdCliente(),
                c.getNombre(),
                c.getDireccion(),
                c.getTelefono(),
                c.getCorreoElectronico()
            };
            modelo.addRow(fila);
        }
    }

