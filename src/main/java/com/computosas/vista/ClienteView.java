public void cargarHistorialCompras(int idCliente, String nombreCliente) {
        try {
            // 1. Conectarse al VentaDAO y traer los datos correspondientes a este ID
            com.computosas.dao.VentaDAO ventaDao = new com.computosas.dao.VentaDAO();
            java.util.List<String[]> compras = ventaDao.obtenerHistorialPorCliente(idCliente);
            
            // 2. Si el cliente no registra compras, avisar cordialmente
            if (compras.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "El cliente " + nombreCliente + " no registra transacciones comerciales previas.", "Historial Vacío", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                return;
            }
            
            // 3. Crear una JTable estructural de forma dinámica para renderizar el reporte técnico
            String[] cabecera = {"Folio de Factura", "Fecha de Compra", "Estatus de Venta", "Total (IVA Inc.)"};
            javax.swing.table.DefaultTableModel modeloReporte = new javax.swing.table.DefaultTableModel(cabecera, 0);
            
            for (String[] compra : compras) {
                modeloReporte.addRow(compra);
            }
            
            javax.swing.JTable tablaReporte = new javax.swing.JTable(modeloReporte);
            javax.swing.JScrollPane contenedor = new javax.swing.JScrollPane(tablaReporte);
            contenedor.setPreferredSize(new java.awt.Dimension(500, 200));
            
            // 4. Desplegar en pantalla como ventana de auditoría gerencial
            javax.swing.JOptionPane.showMessageDialog(this, contenedor, "Historial Indexado de Compras: " + nombreCliente, javax.swing.JOptionPane.PLAIN_MESSAGE);
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al generar el historial indexado: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

