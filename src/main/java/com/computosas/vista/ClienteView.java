    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        // 1. Validar si el usuario seleccionó una fila de la tabla
    int filaSeleccionada = tablaClientes.getSelectedRow();
    
    if (filaSeleccionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Por favor, seleccione el cliente que desea eliminar de la tabla.", 
            "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Obtener el ID del cliente de la columna 0 (primera columna de tu tabla)
    int idCliente = Integer.parseInt(tablaClientes.getValueAt(filaSeleccionada, 0).toString());
    String nombreCliente = tablaClientes.getValueAt(filaSeleccionada, 1).toString();

    // 3. Ventana de confirmación (Buenas prácticas)
    int confirmar = javax.swing.JOptionPane.showConfirmDialog(this, 
        "¿Seguro que deseas eliminar permanentemente al cliente " + nombreCliente + "?", 
        "Confirmar Eliminación", javax.swing.JOptionPane.YES_NO_OPTION);

    if (confirmar == javax.swing.JOptionPane.YES_OPTION) {
        // 4. Instanciar el DAO y ejecutar la eliminación
        com.computosas.dao.ClienteDao clienteDao = new com.computosas.dao.ClienteDao();
        boolean eliminado = clienteDao.eliminarCliente(idCliente);

        if (eliminado) {
            javax.swing.JOptionPane.showMessageDialog(this, "Cliente eliminado correctamente de Neon Cloud.");
            
            // 5. Refrescar la tabla para que desaparezca el registro de inmediato
            // (Reemplaza 'listarClientesPantalla' por el nombre de tu método que recarga la tabla)
            cargarTablaClientes();
            
            // Opcional: Limpiar los campos de texto si el ID quedó escrito
            txtIdCliente.setText("");
            txtNombre.setText("");
            txtDireccion.setText("");
            txtTelefono.setText("");
            txtCorreo.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Error: No se pudo eliminar el cliente de la base de datos.", 
                "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

